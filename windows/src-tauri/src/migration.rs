//! Upgrade app-owned storage and startup registration without discarding user data.
use std::{
    io,
    path::{Path, PathBuf},
};
use tauri_plugin_autostart::ManagerExt;

pub const IDENTIFIER: &str = "com.dadarnie.kumo";

/// The name this app shipped under before the Kumo rebrand.
pub fn legacy_name() -> String {
    "Mimo".to_string()
}

pub fn legacy_identifier() -> String {
    "com.johnpaul.mimo".to_string()
}

fn environment_dir(variable: &str) -> PathBuf {
    std::env::var_os(variable)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("."))
}

pub fn legacy_config_dir() -> PathBuf {
    environment_dir("APPDATA").join(legacy_name())
}

pub fn legacy_hook_path() -> PathBuf {
    environment_dir("LOCALAPPDATA")
        .join(legacy_name())
        .join("bin")
        .join(format!("{}-hook.exe", legacy_name().to_ascii_lowercase()))
}

pub fn migrate_user_data() -> io::Result<()> {
    let old_name = legacy_name();
    for variable in ["APPDATA", "LOCALAPPDATA"] {
        let base = environment_dir(variable);
        migrate_directory(&base.join(&old_name), &base.join("Kumo"))?;
    }
    // The application identifier also chooses WebView2's persistent profile.
    // Copy it before Tauri creates a window, so browser history/settings survive.
    let local = environment_dir("LOCALAPPDATA");
    migrate_directory(&local.join(legacy_identifier()), &local.join(IDENTIFIER))
}

fn migrate_directory(source: &Path, destination: &Path) -> io::Result<()> {
    let marker = destination.join(".kumo-migration-v1");
    if marker.exists() || !source.exists() {
        return Ok(());
    }
    copy_missing(source, destination)?;
    std::fs::write(marker, b"Kumo storage migration completed\n")
}

fn is_redirected(metadata: &std::fs::Metadata) -> bool {
    use std::os::windows::fs::MetadataExt;
    metadata.file_type().is_symlink() || metadata.file_attributes() & 0x400 != 0
}

fn copy_missing(source: &Path, destination: &Path) -> io::Result<()> {
    if is_redirected(&std::fs::symlink_metadata(source)?) {
        return Err(io::Error::other(
            "Storage migration refuses redirected directories.",
        ));
    }
    if let Ok(metadata) = std::fs::symlink_metadata(destination) {
        if is_redirected(&metadata) {
            return Err(io::Error::other(
                "Storage migration refuses redirected directories.",
            ));
        }
    }
    std::fs::create_dir_all(destination)?;
    let old_log = format!("{}.log", legacy_name().to_ascii_lowercase());
    for entry in std::fs::read_dir(source)? {
        let entry = entry?;
        let metadata = std::fs::symlink_metadata(entry.path())?;
        let name = entry.file_name();
        // Helpers are freshly staged from this installation. Cache files are
        // regenerated by WebView2 and may be locked by an older running app.
        if is_redirected(&metadata)
            || matches!(
                name.to_str(),
                Some("bin" | "Cache" | "Code Cache" | "GPUCache" | "Crashpad")
            )
        {
            continue;
        }
        let target = if name == old_log.as_str() {
            destination.join("kumo.log")
        } else {
            destination.join(name)
        };
        if metadata.is_dir() {
            copy_missing(&entry.path(), &target)?;
        } else if metadata.is_file() && !target.exists() {
            let mut output = match std::fs::OpenOptions::new()
                .write(true)
                .create_new(true)
                .open(&target)
            {
                Ok(output) => output,
                Err(error) if error.kind() == io::ErrorKind::AlreadyExists => continue,
                Err(error) => return Err(error),
            };
            let copied = std::fs::File::open(entry.path())
                .and_then(|mut input| io::copy(&mut input, &mut output));
            if let Err(error) = copied {
                drop(output);
                let _ = std::fs::remove_file(target);
                return Err(error);
            }
        }
    }
    Ok(())
}

fn is_legacy_startup(command: &str) -> bool {
    let command = command.trim();
    let executable = if let Some(quoted) = command.strip_prefix('"') {
        quoted.split('"').next().unwrap_or_default()
    } else {
        command.split_whitespace().next().unwrap_or_default()
    };
    Path::new(executable).file_name().is_some_and(|name| {
        name.to_string_lossy()
            .eq_ignore_ascii_case(&format!("{}.exe", legacy_name()))
    })
}

pub fn migrate_autostart(app: &tauri::AppHandle, enabled: bool) {
    use windows::{
        core::{w, PCWSTR},
        Win32::System::Registry::{
            RegCloseKey, RegDeleteValueW, RegOpenKeyExW, RegQueryValueExW, HKEY, HKEY_CURRENT_USER,
            KEY_QUERY_VALUE, KEY_SET_VALUE, REG_SZ,
        },
    };
    unsafe {
        let mut key = HKEY::default();
        if RegOpenKeyExW(
            HKEY_CURRENT_USER,
            w!("Software\\Microsoft\\Windows\\CurrentVersion\\Run"),
            Some(0),
            KEY_QUERY_VALUE | KEY_SET_VALUE,
            &mut key,
        )
        .is_err()
        {
            return;
        }
        let name: Vec<u16> = legacy_name().encode_utf16().chain(Some(0)).collect();
        let mut kind = REG_SZ;
        let mut bytes = 0;
        let value = PCWSTR(name.as_ptr());
        let sized = RegQueryValueExW(key, value, None, Some(&mut kind), None, Some(&mut bytes));
        if sized.is_ok() && kind == REG_SZ && bytes <= 32_768 && bytes % 2 == 0 {
            let mut data = vec![0u16; bytes as usize / 2];
            if RegQueryValueExW(
                key,
                value,
                None,
                Some(&mut kind),
                Some(data.as_mut_ptr().cast()),
                Some(&mut bytes),
            )
            .is_ok()
            {
                let command = String::from_utf16_lossy(&data)
                    .trim_end_matches('\0')
                    .to_string();
                if is_legacy_startup(&command) && (!enabled || app.autolaunch().enable().is_ok()) {
                    let _ = RegDeleteValueW(key, value);
                }
            }
        }
        let _ = RegCloseKey(key);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn storage_migration_preserves_originals_new_settings_and_runs_once() {
        let nonce = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let root =
            std::env::temp_dir().join(format!("mimo-migration-{}-{nonce}", std::process::id()));
        let source = root.join("previous");
        let destination = root.join("Mimo");
        std::fs::create_dir_all(source.join("inbox")).unwrap();
        std::fs::create_dir_all(source.join("bin")).unwrap();
        std::fs::create_dir_all(&destination).unwrap();
        std::fs::write(source.join("settings.json"), b"previous preferences").unwrap();
        std::fs::write(destination.join("settings.json"), b"current preferences").unwrap();
        std::fs::write(source.join("inbox/note.txt"), b"attachment").unwrap();
        std::fs::write(source.join("bin/previous-helper.exe"), b"previous helper").unwrap();
        let old_log = source.join(format!("{}.log", legacy_name().to_ascii_lowercase()));
        std::fs::write(&old_log, b"previous log").unwrap();
        migrate_directory(&source, &destination).unwrap();
        assert_eq!(
            std::fs::read(destination.join("settings.json")).unwrap(),
            b"current preferences"
        );
        assert_eq!(
            std::fs::read(source.join("settings.json")).unwrap(),
            b"previous preferences"
        );
        assert_eq!(
            std::fs::read(destination.join("inbox/note.txt")).unwrap(),
            b"attachment"
        );
        assert_eq!(
            std::fs::read(destination.join("kumo.log")).unwrap(),
            b"previous log"
        );
        assert!(old_log.exists());
        assert!(!destination.join("bin").exists());
        std::fs::remove_file(destination.join("inbox/note.txt")).unwrap();
        migrate_directory(&source, &destination).unwrap();
        assert!(!destination.join("inbox/note.txt").exists());
        std::fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn startup_migration_only_owns_the_previous_app_executable() {
        let previous = format!("C:\\Program Files\\Previous\\{}.exe", legacy_name());
        assert!(is_legacy_startup(&format!("\"{previous}\" --minimized")));
        assert!(!is_legacy_startup("\"C:\\Other\\different.exe\""));
        assert!(!is_legacy_startup(&format!("cmd.exe /c \"{previous}\"")));
    }
}
